#!/usr/bin/env bash
# install.sh — set up AwesomeBrowse 2 and install a launcher + desktop entry.
#
# Usage:  ./install.sh
# Uninstall:
#   rm ~/.local/bin/awesomebrowse
#   rm ~/.local/share/applications/awesomebrowse.desktop
#   rm -rf <repo>/.venv
set -euo pipefail

APP_SLUG="awesomebrowse"
ENTRY_POINT="awesomebrowse_2.1.21_renovo_hotfix.py"
CHOSEN_EDITION="${AWESOMEBROWSE_EDITION:-}"

if [ "${1:-}" = "--edition" ]; then
    if [ -z "${2:-}" ]; then
        echo "error: --edition needs stable or space" >&2
        exit 2
    fi
    CHOSEN_EDITION="$2"
elif [ -n "${1:-}" ]; then
    case "$1" in
        --edition=*) CHOSEN_EDITION="${1#*=}" ;;
        *) echo "usage: ./install.sh [--edition stable|space]" >&2; exit 2 ;;
    esac
fi

if [ -z "$CHOSEN_EDITION" ]; then
    echo "Choose an AwesomeBrowse edition before installing:"
    echo "  1) AwesomeBrowse 2.1.21-Renovo Hotfix"
    echo "  2) AwesomeBrowse 2.1.21-Renovo Hotfix with AwesomeSpace"
    if [ -t 0 ]; then
        printf "Selection [1]: "
        read -r EDITION_CHOICE
    else
        EDITION_CHOICE="1"
    fi
    case "${EDITION_CHOICE:-1}" in
        1|"") CHOSEN_EDITION="stable" ;;
        2) CHOSEN_EDITION="space" ;;
        *) echo "error: choose 1 or 2" >&2; exit 2 ;;
    esac
fi

case "$CHOSEN_EDITION" in
    stable) APP_NAME="AwesomeBrowse 2.1.21-Renovo Hotfix" ;;
    space) APP_NAME="AwesomeBrowse 2.1.21-Renovo Hotfix with AwesomeSpace" ;;
    *) echo "error: edition must be stable or space" >&2; exit 2 ;;
esac

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$REPO_DIR"

BIN_DIR="${XDG_BIN_HOME:-$HOME/.local/bin}"
DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}"
APP_DIR="$DATA_DIR/applications"
VENV_DIR="$REPO_DIR/.venv"
LAUNCHER="$BIN_DIR/$APP_SLUG"
DESKTOP_FILE="$APP_DIR/$APP_SLUG.desktop"
ICON_SRC="$REPO_DIR/icon.png"

# ── sanity checks ────────────────────────────────────────────────────────
if ! command -v python3 >/dev/null 2>&1; then
    echo "error: python3 not found on PATH" >&2
    echo "install it first, e.g.  sudo apt install python3 python3-venv" >&2
    exit 1
fi

if ! python3 -c "import venv" >/dev/null 2>&1; then
    echo "error: python3-venv is not installed" >&2
    echo "on Debian/Ubuntu:  sudo apt install python3-venv" >&2
    echo "on Fedora:         sudo dnf install python3-virtualenv" >&2
    echo "on Arch:           sudo pacman -S python" >&2
    exit 1
fi

if [ ! -f "$ENTRY_POINT" ]; then
    echo "error: $ENTRY_POINT not found in $REPO_DIR" >&2
    exit 1
fi

if [ ! -f "requirements.txt" ]; then
    echo "error: requirements.txt not found in $REPO_DIR" >&2
    exit 1
fi

# ── virtual environment ──────────────────────────────────────────────────
if [ ! -d "$VENV_DIR" ]; then
    echo "→ creating virtual environment in $VENV_DIR"
    python3 -m venv "$VENV_DIR"
fi

# ── python dependencies ──────────────────────────────────────────────────
echo "→ installing Python dependencies"
"$VENV_DIR/bin/pip" install --upgrade pip >/dev/null
"$VENV_DIR/bin/pip" install -r requirements.txt

# ── system libraries (Linux only) ────────────────────────────────────────
if command -v ldconfig >/dev/null 2>&1; then
    echo "→ checking Qt system libraries"
    MISSING=()
    for lib in libnss3.so libasound.so.2 libxkbcommon-x11.so.0 libgl.so.1; do
        if ! ldconfig -p 2>/dev/null | grep -q "$lib"; then
            MISSING+=("$lib")
        fi
    done
    if [ ${#MISSING[@]} -gt 0 ]; then
        echo
        echo "⚠ Some Qt libraries are missing: ${MISSING[*]}"
        echo
        echo "  The browser will install but may not launch until these are present."
        echo "  On Debian/Ubuntu:  sudo apt install libnss3 libasound2 libxkbcommon-x11-0 libgl1"
        echo "  On Fedora:         sudo dnf install nss alsa-lib libxkbcommon-x11 mesa-libGL"
        echo
        echo "  (Continuing anyway. See README 'System requirements' for details.)"
        echo
    fi
fi

# ── verify QtWebEngine actually loads ────────────────────────────────────
echo "→ verifying installation"
VERIFY_LOG="$(mktemp)"
if ! "$VENV_DIR/bin/python" -c "from PyQt6.QtWebEngineWidgets import QWebEngineView" 2>"$VERIFY_LOG"; then
    echo
    echo "✗ QtWebEngine failed to load. Here's the error:"
    echo
    sed 's/^/    /' "$VERIFY_LOG"
    echo
    echo "This usually means a system library is missing. See the README's"
    echo "'System requirements' section for the packages to install."
    rm -f "$VERIFY_LOG"
    exit 1
fi
rm -f "$VERIFY_LOG"
echo "✓ QtWebEngine loads"

# ── launcher script ──────────────────────────────────────────────────────
mkdir -p "$BIN_DIR"
echo "→ writing launcher to $LAUNCHER"
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Auto-generated by install.sh. Delete this file to uninstall.
set -e
export AWESOMEBROWSE_EDITION="$CHOSEN_EDITION"
exec "$VENV_DIR/bin/python" "$REPO_DIR/$ENTRY_POINT" "\$@"
EOF
chmod +x "$LAUNCHER"

# ── desktop entry ────────────────────────────────────────────────────────
mkdir -p "$APP_DIR"

if [ -f "$ICON_SRC" ]; then
    ICON_VALUE="$ICON_SRC"
else
    echo "⚠ icon.png not found in $REPO_DIR — the menu entry will use a generic icon"
    ICON_VALUE="$APP_SLUG"
fi

echo "→ writing desktop entry to $DESKTOP_FILE"
cat > "$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Name=$APP_NAME
Comment=A clean, themeable, Chromium-based browser
Exec=$LAUNCHER
Icon=$ICON_VALUE
Terminal=false
Categories=Network;WebBrowser;
StartupNotify=true
StartupWMClass=AwesomeBrowse2
EOF
chmod +x "$DESKTOP_FILE"

if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$APP_DIR" >/dev/null 2>&1 || true
fi

# ── done ─────────────────────────────────────────────────────────────────
echo
echo "✓ $APP_NAME installed"
echo "  Edition:   $CHOSEN_EDITION"
echo
echo "  Launcher:  $LAUNCHER"
echo "  Menu entry: $DESKTOP_FILE"
echo
echo "  Run it:    $APP_SLUG"
echo

case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *)
        echo "note: $BIN_DIR is not on your PATH."
        echo "      Either add it:"
        echo "          echo 'export PATH=\"\$HOME/.local/bin:\$PATH\"' >> ~/.bashrc"
        echo "      …or run the browser directly:"
        echo "          $LAUNCHER"
        echo
        ;;
esac
